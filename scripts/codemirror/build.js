#!/usr/bin/env node
/**
 * Bundles the admin's JSON editor (CodeMirror 6, entry.js here) into admin/ui/codemirror.js.
 * Run after changing entry.js or the @codemirror/* versions in package.json: npm run build:codemirror.
 * The bundle is committed (the admin deploys from admin/ with no build step).
 */
"use strict";
const path = require("node:path");
const esbuild = require("esbuild");
const ROOT = path.join(__dirname, "..", "..");
esbuild.build({
  entryPoints: [path.join(__dirname, "entry.js")],
  outfile: path.join(ROOT, "admin/ui/codemirror.js"),
  bundle: true, minify: true, format: "iife", target: ["es2020"], legalComments: "eof",
  banner: { js: "/* GENERATED by scripts/codemirror/build.js (CodeMirror 6, MIT license). Do not edit. */" },
}).then(() => console.log("wrote admin/ui/codemirror.js")).catch((e) => { console.error(e.message); process.exit(1); });
